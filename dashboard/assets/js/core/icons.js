/** Glyphs drawn with a fill instead of a stroke. */
const FILLED = new Set(["play", "pointer", "flag"]);

const cache = new Map();

/**
 * Build an icon element.
 *
 * @param {string} name  key from the set above
 * @param {number} [size] pixel size; defaults to inheriting via CSS
 */
export function icon(name, size) {
  const spec = P[name];
  if (!spec) {
    // An unknown glyph renders an empty box rather than throwing. The editor
    // and the renderer both call this with user-supplied names.
    if (!cache.has("__missing")) {
      cache.set("__missing", svg("0 0 24 24", svgEl("rect", { x: 4, y: 4, width: 16, height: 16, rx: 3 })));
    }
    const node = cache.get("__missing").cloneNode(true);
    if (size) sizeIcon(node, size);
    return node;
  }

  if (!cache.has(name)) {
    const parts = Array.isArray(spec) ? spec : [spec];
    const node = svg("0 0 24 24", ...parts.map((d) => svgEl("path", { d })));
    if (FILLED.has(name)) {
      node.setAttribute("fill", "currentColor");
      node.setAttribute("stroke", "none");
    }
    cache.set(name, node);
  }

  const node = cache.get(name).cloneNode(true);
  if (size) sizeIcon(node, size);
  return node;
}

function sizeIcon(node, size) {
  node.style.width = `${size}px`;
  node.style.height = `${size}px`;
}

/** Every available glyph name, for the icon picker. */
export const iconNames = Object.keys(P).sort();

/** True when the name resolves to a real glyph. */
export const hasIcon = (name) => Object.hasOwn(P, name);
